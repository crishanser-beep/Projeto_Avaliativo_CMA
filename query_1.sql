-- query_1 -  Salários por departamento e cargo
-- EMPLOYEES com LEFT JOIN em DEPARDEPARTMENTS e JOBS

--HR.EMPLOYEES
SELECT
    EMPLOYEE_ID,
    FIRST_NAME,
    LAST_NAME,
    EMAIL,
    PHONE_NUMBER,
    HIRE_DATE,
    JOB_ID,
    SALARY,
    COMMISSION_PCT,
    MANAGER_ID,
    DEPARTMENT_ID
FROM
    HR.EMPLOYEES;

--HR.DEPARTAMENTS
SELECT
    DEPARTMENT_ID,
    DEPARTMENT_NAME,
    MANAGER_ID,
    LOCATION_ID
FROM
    HR.DEPARTMENTS;


--HR.JOBS

SELECT
    JOB_ID,
    JOB_TITLE,
    MIN_SALARY,
    MAX_SALARY
FROM
    HR.JOBS;

    SELECT
    funcionarios.EMPLOYEE_ID,
    funcionarios.FIRST_NAME,
    funcionarios.LAST_NAME,
    funcionarios.SALARY,
    departamentos.DEPARTMENT_ID,
    departamentos.DEPARTMENT_NAME
FROM HR.EMPLOYEES funcionarios
LEFT JOIN HR.DEPARTMENTS departamentos
    ON funcionarios.DEPARTMENT_ID = departamentos.DEPARTMENT_ID;

    SELECT COUNT(*) AS TOTAL_FUNCIONARIOS
FROM HR.EMPLOYEES;

SELECT
    d.DEPARTMENT_ID,
    d.DEPARTMENT_NAME,
    j.JOB_ID,
    j.JOB_TITLE,
    COUNT(e.EMPLOYEE_ID) AS TOTAL_FUNCIONARIOS,
    ROUND(AVG(e.SALARY), 2) AS SALARIO_MEDIO,
    MIN(e.SALARY) AS MENOR_SALARIO,
    MAX(e.SALARY) AS MAIOR_SALARIO
FROM HR.EMPLOYEES e
LEFT JOIN HR.DEPARTMENTS d
    ON e.DEPARTMENT_ID = d.DEPARTMENT_ID
LEFT JOIN HR.JOBS j
    ON e.JOB_ID = j.JOB_ID
WHERE e.SALARY IS NOT NULL
GROUP BY
    d.DEPARTMENT_ID,
    d.DEPARTMENT_NAME,
    j.JOB_ID,
    j.JOB_TITLE
ORDER BY
    d.DEPARTMENT_NAME,
    j.JOB_TITLE;